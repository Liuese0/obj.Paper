class I18N(QObject):
    """Singleton-like translation provider. Emits when language changes."""

    languageChanged = pyqtSignal(str)

    def __init__(self):
        super().__init__()
        self._lang = "ko"

    @property
    def lang(self) -> str:
        return self._lang

    def set_lang(self, lang: str) -> None:
        if lang not in ("en", "ko") or lang == self._lang:
            return
        self._lang = lang
        self.languageChanged.emit(lang)

    def toggle(self) -> None:
        self.set_lang("en" if self._lang == "ko" else "ko")

    def t(self, key: str, **fmt) -> str:
        d = KO if self._lang == "ko" else EN
        v = d.get(key, EN.get(key, key))
        if fmt:
            try:
                return v.format(**fmt)
            except Exception:
                return v
        return v


_INSTANCE = I18N()


def i18n() -> I18N:
    return _INSTANCE


def t(key: str, **fmt) -> str:
    return _INSTANCE.t(key, **fmt)
